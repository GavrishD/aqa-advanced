// Task 1: Declaring Variables for Primitive Types

//String
const str = "Practice";
console.log("String:", str);

//Number
const num = 345;
console.log("Number:", num);

//Boolean
const firstExample = 14 >= 14;
const secondExample = 80 < 79;

console.log("First boolean result:", firstExample);
console.log("Second boolean result:", secondExample);

//Null
const nullValue = null;
console.log("null:", nullValue);

//Undefined
let undefinedValue;
console.log("undefined:", undefinedValue);
